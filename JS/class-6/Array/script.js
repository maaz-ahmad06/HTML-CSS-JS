let students = ["Ali", "Ahmad", "Waqas", "Qasim", "Saqib"];
console.log(students);

students.push("Aqib"); // Add element at the last index
console.log(students);

students.pop(); //Remove element from the last
console.log(students);

students.unshift("Aqeel"); // Add element at the first index
console.log(students);

students.shift(); // Remove element from the last
console.log(students);
